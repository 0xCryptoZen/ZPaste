import Foundation

/// A zero-day retention means forever. Pins are always kept by automatic cleanup.
enum HistoryPolicy {
    static func shouldExpire(createdAt: Date, isPinned: Bool, days: Int, now: Date) -> Bool {
        !isPinned && days > 0 && createdAt < now.addingTimeInterval(-Double(days) * 86_400)
    }
}

enum CapturePolicy {
    static func shouldRecord(
        paused: Bool, types: Set<String>, ignoreConfidential: Bool, ignoreTransient: Bool
    ) -> Bool {
        guard !paused else { return false }
        if ignoreConfidential && types.contains("org.nspasteboard.ConcealedType") { return false }
        if ignoreTransient && !types.isDisjoint(with: [
            "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"
        ]) { return false }
        return true
    }
}

/// Match the exact write, so a user copy made before the next poll is never swallowed.
struct ClipboardWriteSuppression {
    private var ownChangeCount: Int?

    mutating func recordWrite(changeCount: Int) {
        ownChangeCount = changeCount
    }

    mutating func shouldIgnore(changeCount: Int) -> Bool {
        defer { ownChangeCount = nil }
        return ownChangeCount == changeCount
    }
}

/// Never send into ZPaste, a different application, or with clipboard content changed mid-flight.
enum PasteDeliveryPolicy {
    static func canSend(
        targetPID: Int32, frontmostPID: Int32?, ownPID: Int32,
        targetTerminated: Bool, clipboardUnchanged: Bool, cancelled: Bool
    ) -> Bool {
        targetPID != ownPID && targetPID == frontmostPID && !targetTerminated && clipboardUnchanged && !cancelled
    }
}
