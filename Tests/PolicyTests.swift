import Foundation

@main
struct PolicyTests {
    static func main() {
        let now = Date(timeIntervalSince1970: 2_000_000_000)
        let old = now.addingTimeInterval(-8 * 86_400)
        precondition(HistoryPolicy.shouldExpire(createdAt: old, isPinned: false, days: 7, now: now))
        precondition(!HistoryPolicy.shouldExpire(createdAt: old, isPinned: true, days: 7, now: now))
        precondition(!HistoryPolicy.shouldExpire(createdAt: old, isPinned: false, days: 0, now: now))
        precondition(!HistoryPolicy.shouldExpire(createdAt: now, isPinned: false, days: 7, now: now))
        precondition(!HistoryPolicy.shouldExpire(createdAt: now.addingTimeInterval(-7 * 86_400), isPinned: false, days: 7, now: now))

        precondition(!CapturePolicy.shouldRecord(paused: true, types: [], ignoreConfidential: false, ignoreTransient: false))
        precondition(!CapturePolicy.shouldRecord(paused: false, types: ["org.nspasteboard.ConcealedType"], ignoreConfidential: true, ignoreTransient: false))
        precondition(CapturePolicy.shouldRecord(paused: false, types: ["org.nspasteboard.ConcealedType"], ignoreConfidential: false, ignoreTransient: true))
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            precondition(!CapturePolicy.shouldRecord(paused: false, types: [type], ignoreConfidential: false, ignoreTransient: true))
        }
        precondition(CapturePolicy.shouldRecord(paused: false, types: ["public.utf8-plain-text"], ignoreConfidential: true, ignoreTransient: true))

        var suppression = ClipboardWriteSuppression()
        suppression.recordWrite(changeCount: 10)
        precondition(suppression.shouldIgnore(changeCount: 10))
        precondition(!suppression.shouldIgnore(changeCount: 11))
        suppression.recordWrite(changeCount: 12)
        precondition(!suppression.shouldIgnore(changeCount: 13), "A new user copy must not be skipped if polling missed our write")
        precondition(PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: 10, ownPID: 20, targetTerminated: false, clipboardUnchanged: true, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: 20, ownPID: 20, targetTerminated: false, clipboardUnchanged: true, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 20, frontmostPID: 20, ownPID: 20, targetTerminated: false, clipboardUnchanged: true, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: nil, ownPID: 20, targetTerminated: false, clipboardUnchanged: true, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: 10, ownPID: 20, targetTerminated: true, clipboardUnchanged: true, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: 10, ownPID: 20, targetTerminated: false, clipboardUnchanged: false, cancelled: false))
        precondition(!PasteDeliveryPolicy.canSend(targetPID: 10, frontmostPID: 10, ownPID: 20, targetTerminated: false, clipboardUnchanged: true, cancelled: true))
        print("Policy tests passed: retention, pinned protection, privacy, pause, and clipboard write suppression")
    }
}
